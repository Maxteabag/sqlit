"""PostgreSQL identity completion for integer column definitions."""

import re

# PostgreSQL accepts any high byte in identifiers and dollar tags. Dollar
# signs can continue an identifier, but they cannot occur inside the tag.
_NAME_START = r"a-zA-Z_\x80-\U0010ffff"
_TAG_CONTINUE = _NAME_START + "0-9"
_NAME_CONTINUE = _TAG_CONTINUE + "$"
_IDENTIFIER = rf'(?:"(?:[^"]|"")+"|[{_NAME_START}][{_NAME_CONTINUE}]*)'
_TABLE = rf"{_IDENTIFIER}(?:\s*\.\s*{_IDENTIFIER})?"
_CREATE = re.compile(
    rf"\s*CREATE\s+(?:(?:TEMP(?:ORARY)?|UNLOGGED)\s+)?TABLE\s+"
    rf"(?:IF\s+NOT\s+EXISTS\s+)?{_TABLE}\s*\(",
    re.IGNORECASE | re.ASCII,
)
_ALTER = re.compile(rf"\s*ALTER\s+TABLE\s+{_TABLE}\s+", re.IGNORECASE | re.ASCII)
_ADD = re.compile(r"\s*ADD\s+(?:COLUMN\s+)?(?:IF\s+NOT\s+EXISTS\s+)?", re.IGNORECASE | re.ASCII)
_INTEGER_TYPE = r"(?:pg_catalog\.)?(?:smallint|integer|bigint|int[248]?)"
_COLUMN = re.compile(
    rf"\s*{_IDENTIFIER}\s+{_INTEGER_TYPE}(?:\s+(?:NOT\s+NULL|PRIMARY\s+KEY|UNIQUE))*"
    r"\s+([a-z\s]+)",
    re.IGNORECASE | re.ASCII,
)
_CLAUSES = ("GENERATED ALWAYS AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY")
_CLAUSE_WORDS = {word for clause in _CLAUSES for word in clause.split()}
_CLAUSE_PREFIXES = {word[:end] for word in _CLAUSE_WORDS for end in range(1, len(word) + 1)}
_COLUMN_TAIL_WORDS = _CLAUSE_WORDS | {"NOT", "NULL", "PRIMARY", "KEY", "UNIQUE"}
_TAIL_WORD = re.compile(
    rf"(?<![{_NAME_CONTINUE}.])(?:pg_catalog\.)?[a-z]+[248]?\Z",
    re.IGNORECASE | re.ASCII,
)
_MAX_TAIL_WORD = len("pg_catalog.smallint")
_SPACE = " \t\n\r\f\v"
_LINE_END = re.compile(r"[\r\n]")
_BLOCK_DELIMITER = re.compile(r"/\*|\*/")
_STRING = re.compile(r"'(?:[^']|'')*'(?!')")
_ESCAPE_STRING = re.compile(r"'(?:[^'\\]|''|\\[\s\S])*'(?!')")
_ESCAPE_CONTINUATION = re.compile(r"(?:[ \t\f\v]*(?:--[^\r\n]*)?[\r\n])+[ \t\f\v]*'")
_QUOTED_IDENTIFIER = re.compile(r'"(?:[^"]|"")*"(?!")')
_CONTEXT_TOKEN = re.compile(
    r"(?P<comment>/\*|--)|(?P<quote>[Ee]'|['\"])"
    rf"|(?P<dollar>\$(?:[{_NAME_START}][{_TAG_CONTINUE}]*)?\$)"
    # Consume complete unquoted identifiers so their interior dollar signs
    # and any trailing E cannot be mistaken for literal openers.
    rf"|[{_NAME_START}][{_NAME_CONTINUE}]*|(?P<punct>[();,])"
)


def _has_identity_candidate(sql: str) -> bool:
    """Reject ordinary completion requests using only the suffix at the cursor."""
    position = len(sql)
    at_cursor = True
    while position:
        end = position
        while position and sql[position - 1] in _SPACE:
            position -= 1

        # A comment can stand in for whitespace anywhere in the column
        # definition. Let the forward scanner resolve ambiguous boundaries.
        if sql.endswith("*/", 0, position):
            return True
        if _LINE_END.search(sql, position, end):
            line = position
            while line and sql[line - 1] not in "\r\n":
                line -= 1
            if sql.find("--", line, position) != -1:
                return True

        word = _TAIL_WORD.search(sql, max(0, position - _MAX_TAIL_WORD), position)
        if not word:
            return False
        if not at_cursor and re.fullmatch(
            _INTEGER_TYPE, word[0], re.IGNORECASE | re.ASCII
        ):
            return word.start() > 0 and (
                sql[word.start() - 1] in _SPACE or sql.endswith("*/", 0, word.start())
            )
        if word[0].upper() not in (_CLAUSE_PREFIXES if at_cursor else _COLUMN_TAIL_WORDS):
            return False
        at_cursor = False
        position = word.start()
    return False


def _block_comment_end(sql: str, start: int) -> int | None:
    depth = 1
    for delimiter in _BLOCK_DELIMITER.finditer(sql, start + 2):
        depth += 1 if delimiter[0] == "/*" else -1
        if depth == 0:
            return delimiter.end()
    return None


def _quoted_end(sql: str, start: int, token: str) -> int | None:
    if token == '"':
        match = _QUOTED_IDENTIFIER.match(sql, start)
    elif token == "'":
        match = _STRING.match(sql, start)
    else:
        match = _ESCAPE_STRING.match(sql, start + 1)
        while match and (continued := _ESCAPE_CONTINUATION.match(sql, match.end())):
            match = _ESCAPE_STRING.match(sql, continued.end() - 1)
    return match.end() if match else None


def _scan_context(sql: str) -> str | None:
    """Locate the active column definition, with comments replaced by spaces."""
    statement_start = item_start = alter_item_start = depth = 0
    outer_open = -1
    position = unmasked_start = 0
    parts: list[str] = []
    while match := _CONTEXT_TOKEN.search(sql, position):
        start, position = match.span()
        token = match[0]
        if match.lastgroup == "comment":
            if token == "/*":
                end = _block_comment_end(sql, start)
            else:
                newline = _LINE_END.search(sql, position)
                end = newline.start() if newline else None
            if end is None:
                return None
            parts.extend((sql[unmasked_start:start], " " * (end - start)))
            position = unmasked_start = end
        elif match.lastgroup == "quote":
            end = _quoted_end(sql, start, token)
            if end is None:
                return None
            position = end
        elif match.lastgroup == "dollar":
            close = sql.find(token, position)
            if close == -1:
                return None
            position = close + len(token)
        elif match.lastgroup == "punct":
            if token == ";":
                statement_start = item_start = alter_item_start = position
                depth = 0
                parts.clear()
                unmasked_start = position
            elif token == "(":
                if depth == 0:
                    outer_open = start
                depth += 1
            elif token == ")":
                depth -= 1
            elif depth == 1:
                item_start = position
            elif depth == 0:
                alter_item_start = position

    statement = "".join([*parts, sql[unmasked_start:]]) if parts else sql[statement_start:]
    create = _CREATE.match(statement)
    if create and depth == 1 and outer_open == statement_start + create.end() - 1:
        return statement[max(create.end(), item_start - statement_start):]

    alter = _ALTER.match(statement)
    if alter and depth == 0:
        action = statement[max(alter.end(), alter_item_start - statement_start):]
        if add := _ADD.match(action):
            return action[add.end():]
    return None


def get_postgres_identity_completions(before_cursor: str) -> list[str] | None:
    if not _has_identity_candidate(before_cursor):
        return None

    column = _scan_context(before_cursor)
    if column is None:
        return None

    match = _COLUMN.fullmatch(column)
    if not match:
        return None

    typed = match[1].upper()
    words = typed.split()
    if not words:
        return None
    # The editor replaces only the current word when accepting a suggestion.
    completed_words = len(words) - int(not typed[-1].isspace())
    prefix = " ".join(words) + (" " if typed[-1].isspace() else "")
    matches = [
        " ".join(clause.split()[completed_words:])
        for clause in _CLAUSES
        if clause.startswith(prefix) and clause != prefix
    ]
    if not matches:
        return None

    # Keep the single keyword first when the same prefix can continue a
    # computed column. The dropdown selects the first match for plain Tab.
    if completed_words == 0:
        matches.insert(0, "GENERATED")
    elif words[:-1] in (["GENERATED"], ["GENERATED", "ALWAYS"]) and prefix.endswith((" A", " AS")):
        matches.insert(0, "AS")
    return matches
