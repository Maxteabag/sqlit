"""PostgreSQL identity completion for integer column definitions."""

import re

from sqlparse import tokens
from sqlparse.lexer import tokenize

_IDENTIFIER = r'(?:"(?:[^"]|"")+"|[a-z_][\w$]*)'
_TABLE = rf"{_IDENTIFIER}(?:\s*\.\s*{_IDENTIFIER})?"
_CREATE = re.compile(
    rf"\s*CREATE\s+(?:(?:TEMP(?:ORARY)?|UNLOGGED)\s+)?TABLE\s+"
    rf"(?:IF\s+NOT\s+EXISTS\s+)?{_TABLE}\s*\(",
    re.IGNORECASE,
)
_ALTER = re.compile(rf"\s*ALTER\s+TABLE\s+{_TABLE}\s+", re.IGNORECASE)
_ADD = re.compile(r"\s*ADD\s+(?:COLUMN\s+)?(?:IF\s+NOT\s+EXISTS\s+)?", re.IGNORECASE)
_COLUMN = re.compile(
    rf"\s*{_IDENTIFIER}\s+(?:pg_catalog\.)?"
    r"(?:smallint|integer|bigint|int[248]?)(?:\s+(?:NOT\s+NULL|PRIMARY\s+KEY|UNIQUE))*"
    r"\s+([a-z\s]+)",
    re.IGNORECASE,
)
_CLAUSES = ("GENERATED ALWAYS AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY")


def get_postgres_identity_completions(before_cursor: str) -> list[str] | None:
    statement_start = item_start = depth = 0
    outer_open = -1
    alter_item_start = 0
    position = 0
    for kind, value in tokenize(before_cursor):
        if kind in tokens.Punctuation:
            if value == ";":
                statement_start = item_start = alter_item_start = position + 1
                depth = 0
            elif value == "(":
                if depth == 0:
                    outer_open = position
                depth += 1
            elif value == ")":
                depth -= 1
            elif value == ",":
                if depth == 1:
                    item_start = position + 1
                elif depth == 0:
                    alter_item_start = position + 1
        position += len(value)

    statement = before_cursor[statement_start:]
    create = _CREATE.match(statement)
    alter = _ALTER.match(statement)
    if create and depth == 1 and outer_open == statement_start + create.end() - 1:
        column = before_cursor[max(statement_start + create.end(), item_start):]
    elif alter and depth == 0:
        action = before_cursor[max(statement_start + alter.end(), alter_item_start):]
        add = _ADD.match(action)
        if not add:
            return None
        column = action[add.end():]
    else:
        return None

    match = _COLUMN.fullmatch(column)
    if not match:
        return None

    typed = match[1].upper()
    words = typed.split()
    if not words:
        return None
    # The editor replaces only the current word when accepting a suggestion.
    completed_words = len(words) - int(not typed[-1].isspace())
    prefix = " ".join(words) + (" " if typed[-1].isspace() else "")
    matches = [
        " ".join(clause.split()[completed_words:])
        for clause in _CLAUSES
        if clause.startswith(prefix) and clause != prefix
    ]
    return matches or None
