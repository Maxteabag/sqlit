"""PostgreSQL identity completion for integer column definitions."""

import re

from sqlparse import tokens
from sqlparse.lexer import tokenize

_IDENTIFIER = r'(?:"(?:[^"]|"")+"|[a-z_][\w$]*)'
_TABLE = rf"{_IDENTIFIER}(?:\s*\.\s*{_IDENTIFIER})?"
_CREATE = re.compile(
    rf"\s*CREATE\s+(?:(?:TEMP(?:ORARY)?|UNLOGGED)\s+)?TABLE\s+"
    rf"(?:IF\s+NOT\s+EXISTS\s+)?{_TABLE}\s*\(",
    re.IGNORECASE,
)
_ALTER = re.compile(rf"\s*ALTER\s+TABLE\s+{_TABLE}\s+", re.IGNORECASE)
_ADD = re.compile(r"\s*ADD\s+(?:COLUMN\s+)?(?:IF\s+NOT\s+EXISTS\s+)?", re.IGNORECASE)
_COLUMN = re.compile(
    rf"\s*{_IDENTIFIER}\s+(?:pg_catalog\.)?"
    r"(?:smallint|integer|bigint|int[248]?)(?:\s+(?:NOT\s+NULL|PRIMARY\s+KEY|UNIQUE))*"
    r"\s+([a-z\s]+)",
    re.IGNORECASE,
)
# A necessary condition only. The lexer decides whether the keyword is
# outside comments and literals and starts the statement at the cursor.
_DDL_KEYWORD = re.compile(r"\b(?:CREATE|ALTER)\b", re.IGNORECASE)
_BLOCK_DELIMITER = re.compile(r"/\*|\*/")
_STRING = re.compile(r"'(?:[^']|'')*'(?!')")
_ESCAPE_STRING = re.compile(r"[Ee]'(?:[^'\\]|''|\\[\s\S])*'(?!')")
_QUOTED_IDENTIFIER = re.compile(r'"(?:[^"]|"")*"(?!")')
_DOLLAR_QUOTE = re.compile(r"(?<![\w$])\$(?:[^\W\d]\w*)?\$")
_CLAUSES = ("GENERATED ALWAYS AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY")


def _has_identity_prefix(before_cursor: str) -> bool:
    # Read at most the five words of a clause, starting at the cursor.
    # The full lexer still validates the DDL context.
    position = len(before_cursor)
    prefix = " " if before_cursor and before_cursor[-1].isspace() else ""
    for _ in range(5):
        while position and before_cursor[position - 1].isspace():
            position -= 1
        end = position
        while position and not before_cursor[position - 1].isspace():
            position -= 1
            if end - position > len("GENERATED"):
                return False
        if end == position:
            return False
        word = before_cursor[position:end].upper()
        prefix = word + (" " if prefix and prefix != " " else "") + prefix
        if any(clause.startswith(prefix) and clause != prefix for clause in _CLAUSES):
            return True
    return False


def _block_comment_end(sql: str, start: int) -> int | None:
    depth = 1
    for delimiter in _BLOCK_DELIMITER.finditer(sql, start + 2):
        depth += 1 if delimiter[0] == "/*" else -1
        if depth == 0:
            return delimiter.end()
    return None


def _postgres_span(sql: str, position: int, value: str) -> tuple[int, bool] | None:
    """Return the token's end and whether it is a PostgreSQL comment."""
    end = position + len(value)
    if sql.startswith("/*", position):
        # PostgreSQL nests block comments. sqlparse closes at the first */.
        comment_end = _block_comment_end(sql, position)
        return (comment_end, True) if comment_end is not None else None
    if value.startswith("--"):
        if end == len(sql) and not value.endswith(("\r", "\n")):
            return None
        return end, True

    # sqlparse can split escape strings or unfinished literals into SQL tokens.
    quoted = None
    if value[0] == "'":
        quoted = _STRING
    elif value[0] == '"':
        quoted = _QUOTED_IDENTIFIER
    elif sql[position:position + 2].lower() == "e'":
        quoted = _ESCAPE_STRING
    if quoted is not None:
        match = quoted.match(sql, position)
        return (match.end(), False) if match else None

    if value.startswith("$") and (tag := _DOLLAR_QUOTE.match(sql, position)):
        close = sql.find(tag[0], tag.end())
        return (close + len(tag[0]), False) if close != -1 else None
    return end, False


def get_postgres_identity_completions(before_cursor: str) -> list[str] | None:
    if not _has_identity_prefix(before_cursor) or not _DDL_KEYWORD.search(before_cursor):
        return None

    statement_start = item_start = depth = 0
    outer_open = -1
    alter_item_start = 0
    position = unmasked_start = 0
    parts: list[str] = []
    lexer = tokenize(before_cursor)
    while position < len(before_cursor):
        kind, value = next(lexer)
        lexer_end = position + len(value)
        span = _postgres_span(before_cursor, position, value)
        if span is None:
            return None
        end, is_comment = span
        if is_comment:
            # Preserve offsets used for the statement and column boundaries.
            parts.extend((before_cursor[unmasked_start:position], " " * (end - position)))
            unmasked_start = end
        elif kind in tokens.Punctuation:
            if value == ";":
                statement_start = item_start = alter_item_start = position + 1
                depth = 0
            elif value == "(":
                if depth == 0:
                    outer_open = position
                depth += 1
            elif value == ")":
                depth -= 1
            elif value == ",":
                if depth == 1:
                    item_start = position + 1
                elif depth == 0:
                    alter_item_start = position + 1

        # Skip any extra lexer tokens inside a PostgreSQL literal or comment.
        while lexer_end < end:
            _, skipped = next(lexer)
            lexer_end += len(skipped)
        if lexer_end != end:
            # A token crossed the end of the span. Start again at its boundary.
            lexer = tokenize(before_cursor[end:])
        position = end

    clean = "".join([*parts, before_cursor[unmasked_start:]]) if parts else before_cursor
    statement = clean[statement_start:]
    create = _CREATE.match(statement)
    alter = _ALTER.match(statement)
    if create and depth == 1 and outer_open == statement_start + create.end() - 1:
        column = clean[max(statement_start + create.end(), item_start):]
    elif alter and depth == 0:
        action = clean[max(statement_start + alter.end(), alter_item_start):]
        add = _ADD.match(action)
        if not add:
            return None
        column = action[add.end():]
    else:
        return None

    match = _COLUMN.fullmatch(column)
    if not match:
        return None

    typed = match[1].upper()
    words = typed.split()
    if not words:
        return None
    # The editor replaces only the current word when accepting a suggestion.
    completed_words = len(words) - int(not typed[-1].isspace())
    prefix = " ".join(words) + (" " if typed[-1].isspace() else "")
    matches = [
        " ".join(clause.split()[completed_words:])
        for clause in _CLAUSES
        if clause.startswith(prefix) and clause != prefix
    ]
    if not matches:
        return None

    # Keep the single keyword first when the same prefix can continue a
    # computed column. The dropdown selects the first match for plain Tab.
    if completed_words == 0:
        matches.insert(0, "GENERATED")
    elif words[:-1] in (["GENERATED"], ["GENERATED", "ALWAYS"]) and prefix.endswith((" A", " AS")):
        matches.insert(0, "AS")
    return matches
